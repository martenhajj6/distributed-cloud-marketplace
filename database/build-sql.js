const fs = require('fs');
const path = require('path');

// These lists are deliberately explicit: table dependencies determine the order.
const modules = {
    schema: ['00_database', '01_auth', '02_providers', '03_networking',
        '04_resources', '05_usage_and_logs', '07_procedures', '08_triggers', '09_views'],
    seed: ['01_demo_users', '02_demo_providers', '03_demo_resources']
};

for (const [kind, files] of Object.entries(modules)) {
    const sql = `-- Generated by node database/build-sql.js; edit database/${kind}/ modules.\n`
        + files.map(name => fs.readFileSync(path.join(__dirname, kind, `${name}.sql`), 'utf8')).join('');
    const target = path.join(__dirname, `${kind}.sql`);
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(target, 'utf8') !== sql) {
            throw new Error(`${kind}.sql is stale; run npm run db:build`);
        }
        console.log(`${kind}.sql matches its canonical modules`);
    } else {
        fs.writeFileSync(target, sql);
        console.log(`Generated ${kind}.sql`);
    }
}
